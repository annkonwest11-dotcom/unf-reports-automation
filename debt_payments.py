# -*- coding: utf-8 -*-
"""Оплаты клиентов из 1С — общий слой для отчёта по дебиторке и борда.

Долг в обоих отчётах — остаток по расходным накладным (fetch_base в
sync_debitorka). Сам по себе он не отвечает на вопрос «а клиент вообще платит?»
— для этого здесь две выгрузки:

  fetch_payments  — когда и сколько клиент платил (документы поступлений);
  fetch_unapplied — его деньги, которые долг НЕ гасят, потому что не разнесены
                    по накладным или разнесены на накладную с минусом.

Модуль держим отдельным файлом, а не внутри debt_report.py: тот при импорте
собирает весь отчёт (кода на уровне модуля), и борду его импортировать нельзя.
"""
import datetime
import re
from collections import defaultdict

from sync_odata import _fetch_odata

ИСТОРИЯ_ОПЛАТ = 180      # на сколько дней назад тянем оплаты


def contractor_names(base_id):
    """{Ref_Key: имя} — те же имена, что и в дебиторке."""
    return {c["Ref_Key"]: c.get("Description", "")
            for c in _fetch_odata(base_id, "Catalog_Контрагенты")}


def fetch_payments(base_id, asof, days=ИСТОРИЯ_ОПЛАТ):
    """Оплаты ОТ ПОКУПАТЕЛЕЙ: {Контрагент_Key: [(дата, сумма, куда), …]}.

    Источник — документы ПоступлениеНаСчет и ПоступлениеВКассу (проведённые, не
    помеченные на удаление, вид операции «ОтПокупателя»: иначе в сумму попадут
    возвраты поставщиков и личные средства предпринимателя). Берём именно
    документы, а не регистр: регистр отдаёт записи, вложенные в RecordSet по
    регистратору, и по дате не фильтруется.
    """
    since = asof - datetime.timedelta(days=days)
    по_клиенту = defaultdict(list)
    for сущность, куда in (("Document_ПоступлениеНаСчет", "счёт"),
                           ("Document_ПоступлениеВКассу", "касса")):
        запрос = (f"{сущность}?$select=Date,Контрагент_Key,СуммаДокумента,ВидОперации"
                  f"&$filter=Date ge datetime'{since}T00:00:00'"
                  f" and Posted eq true and DeletionMark eq false")
        for d in _fetch_odata(base_id, запрос):
            if d.get("ВидОперации") != "ОтПокупателя":
                continue
            сумма = float(d.get("СуммаДокумента") or 0)
            ключ = d.get("Контрагент_Key")
            if сумма <= 0 or not ключ:
                continue
            по_клиенту[ключ].append(
                (datetime.datetime.fromisoformat(d["Date"]), сумма, куда))
    for v in по_клиенту.values():
        v.sort(key=lambda x: x[0])
    return по_клиенту


def fetch_unapplied(base_id, asof):
    """Деньги клиента, которые НЕ гасят его долг: {Контрагент_Key: (оплата, переплата)}.

    Долг — это сумма расходных накладных с ПОЛОЖИТЕЛЬНЫМ остатком, минусы отчёт
    не нетует. Поэтому клиент числится должником, хотя уже заплатил, в двух
    случаях:
      * «оплата» — деньги висят отдельной записью (поступление, аванс) и не
        разнесены ни по одной накладной;
      * «переплата» — деньги разнесены, но на накладную с минусом: по одной
        накладной переплата, по другой долг. Так было у ГЛОБАЛ ФРУТ СИТИ:
        −11 970 ₽ на одной накладной при долге 11 970 ₽ на двух других, из-за
        чего он 350 дней висел в просрочке, хотя не должен ничего.
    """
    bal = _fetch_odata(
        base_id,
        f"AccumulationRegister_РасчетыСПокупателями/Balance(Period=datetime'{asof}T00:00:00')")
    agg = defaultdict(lambda: [0.0, 0.0])
    for b in bal:
        сумма = b.get("СуммаBalance", 0) or 0
        if сумма >= 0:
            continue
        накладная = b.get("Документ_Type", "").endswith("РасходнаяНакладная")
        agg[b["Контрагент_Key"]][1 if накладная else 0] += -сумма
    return {k: (round(v[0], 2), round(v[1], 2))
            for k, v in agg.items() if round(v[0] + v[1]) > 0}


def by_name(base_id, asof):
    """Оплаты и «висящие» деньги базы в разрезе ИМЁН контрагентов.

    Имена берём из того же справочника, что и дебиторка, поэтому ключ склейки с
    записями fetch_base — имя; дублей имён среди должников нет (проверено
    13.10.2026 по всем трём базам).
    """
    имена = contractor_names(base_id)
    оплаты = defaultdict(list)
    for k, список in fetch_payments(base_id, asof).items():
        оплаты[имена.get(k, k)].extend(список)
    for v in оплаты.values():
        v.sort(key=lambda x: x[0])
    висят = defaultdict(lambda: [0.0, 0.0])
    for k, (оплата, переплата) in fetch_unapplied(base_id, asof).items():
        висят[имена.get(k, k)][0] += оплата
        висят[имена.get(k, k)][1] += переплата
    return оплаты, висят


# служебные пометки в названиях 1С — в бренд клиента не входят
СТОП = {"dsbx", "эдо", "сбис", "счет", "счёт", "нал", "наличка", "1с",
        "ликвидирован", "смотреть"}


def бренд(name):
    """Имя до скобки без служебных хвостов — чтобы свести клиента по всем ИП.

    Клиента переводят с юрлица на юрлицо, старые накладные остаются на прежнем
    ИП: «СИКСТИ (ООО ЛЕО)» и «СИКСТИ (ООО ЛЕО) с 10.08.26 на ПЕРФИЛЬЕВ» —
    один клиент для обзвона.
    """
    s = name.lower().replace("ё", "е")
    s = re.split(r"[(\[]", s)[0]
    s = re.sub(r"\bс\s+\d{2}\.\d{2}\.\d{2}\b.*$", " ", s)
    s = re.sub(r"\bна\s+ип\b.*$", " ", s)
    s = s.replace("«", " ").replace("»", " ").replace('"', " ").replace("'", " ")
    s = re.sub(r"[!?]+", " ", s)
    токены = []
    for t in s.split():
        t = re.sub(r"\b(наличка|нал|эдо|сбис|dsbx|1с)\b", "", t).strip("/-. ")
        if not t or t in СТОП:
            continue
        токены.append(t)
    while токены and токены[-1] in {"в", "к", "на", "с", "и"}:
        токены.pop()
    return " ".join(токены).strip() or s.strip()
